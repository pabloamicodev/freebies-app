/**
 * UI extensions have no runtime env, so the app host is baked in at deploy time.
 * Usage: node scripts/write-extension-app-url.mjs <shopify.app*.toml>
 * Rewrites app-url.ts of the checkout and customer-account extensions from that
 * toml's application_url. The committed files default to HPN.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ADMIN = join(dirname(fileURLToPath(import.meta.url)), "../apps/shopify-admin");
export const TARGETS = ["checkout-ui", "customer-account-ui"].map((ext) =>
  join(ADMIN, "extensions", ext, "src/app-url.ts"),
);

export function readApplicationUrl(tomlText) {
  const m = tomlText.match(/^application_url\s*=\s*"(https:\/\/[^"]+)"/m);
  if (!m) throw new Error("application_url not found");
  return m[1].replace(/\/+$/, "");
}

export function renderAppUrlModule(url) {
  return [
    "// Generated by scripts/write-extension-app-url.mjs from the deploy config's application_url.",
    `export const APP_URL = "${url}";`,
    "",
  ].join("\r\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const config = process.argv[2];
  if (!config) throw new Error("usage: write-extension-app-url.mjs <toml>");
  const url = readApplicationUrl(readFileSync(resolve(ADMIN, config), "utf8"));
  for (const file of TARGETS) writeFileSync(file, renderAppUrlModule(url));
  console.log(`extension APP_URL -> ${url}`);
}
